//=================================================测试结果结构================================================
typedef struct
{
    // 测试基本信息
    char test_name[32];                         // 测试名称
    uint32 test_duration;                       // 测试时长 (ms)
    bool test_passed;                           // 测试是否通过
    
    // 性能指标
    float max_error;                            // 最大误差
    float average_error;                        // 平均误差
    float rms_error;                            // 均方根误差
    uint32 settle_time;                         // 稳定时间 (ms)
    float overshoot;                            // 超调量 (%)
    
    // 统计数据
    uint32 sample_count;                        // 采样次数
    uint32 error_count;                         // 错误次数
    float success_rate;                         // 成功率 (%)
    
} test_result_struct;

