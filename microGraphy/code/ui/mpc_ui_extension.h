//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示MPC自动调参界面
// 参数说明     void
// 返回参数     void
// 使用示例     mpc_ui_show_auto_tuning();
//-------------------------------------------------------------------------------------------------------------------
void mpc_ui_show_auto_tuning(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示自动调参配置界面
// 参数说明     void
// 返回参数     void
// 使用示例     mpc_ui_show_tuning_config();
//-------------------------------------------------------------------------------------------------------------------
void mpc_ui_show_tuning_config(void);

