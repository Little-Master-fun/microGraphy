#ifndef _SHOW_IPS_LJMNB_IMPROVED_H_
#define _SHOW_IPS_LJMNB_IMPROVED_H_

#include "zf_common_typedef.h"
#include "config_navigation.h"

//=================================================系统模式枚举================================================
typedef enum {
    UI_MODE0 = 0,                               // 模式0：主界面
    UI_MODE1 = 1,                               // 模式1：参数设置
    UI_MODE2 = 2,                               // 模式2：参数调整
    UI_MODE3 = 3,                               // 模式3：运行控制
    UI_MODE_MAX
} ui_system_mode_enum;

//=================================================按键枚举定义================================================
typedef enum {
    UI_KEY2_PARAM_0 = 0,                        // 参数0：X1坐标
    UI_KEY2_PARAM_1 = 1,                        // 参数1：Y1坐标
    UI_KEY2_PARAM_2 = 2,                        // 参数2：X2坐标
    UI_KEY2_PARAM_3 = 3,                        // 参数3：Y2坐标
    UI_KEY2_PARAM_4 = 4,                        // 参数4：X3坐标
    UI_KEY2_PARAM_5 = 5,                        // 参数5：Y3坐标
    UI_KEY2_PARAM_6 = 6,                        // 参数6：X4坐标
    UI_KEY2_PARAM_7 = 7,                        // 参数7：Y4坐标
    UI_KEY2_PARAM_8 = 8,                        // 参数8：X5坐标
    UI_KEY2_PARAM_9 = 9,                        // 参数9：Y5坐标
    UI_KEY2_PARAM_10 = 10,                      // 参数10：X6坐标
    UI_KEY2_PARAM_11 = 11,                      // 参数11：Y6坐标
    UI_KEY2_PARAM_MAX
} ui_key2_param_enum;

typedef enum {
    UI_KEY3_INCREASE = 0,                       // 按键3：增加参数值
    UI_KEY3_SAVE = 1,                           // 按键3：保存参数
    UI_KEY3_MAX
} ui_key3_action_enum;

typedef enum {
    UI_KEY4_DECREASE = 0,                       // 按键4：减少参数值
    UI_KEY4_RESET = 1,                          // 按键4：重置参数
    UI_KEY4_MAX
} ui_key4_action_enum;

//=================================================UI状态结构================================================
typedef struct
{
    ui_system_mode_enum current_mode;           // 当前系统模式
    ui_key2_param_enum current_param;           // 当前选择的参数
    ui_key3_action_enum key3_action;            // KEY3动作
    ui_key4_action_enum key4_action;            // KEY4动作
    
    // 按键状态
    bool key1_pressed;                          // KEY1按下标志
    bool key1_last_state;                       // KEY1上次状态
    bool key2_pressed;                          // KEY2按下标志
    bool key2_last_state;                       // KEY2上次状态
    bool key3_pressed;                          // KEY3按下标志
    bool key3_last_state;                       // KEY3上次状态
    bool key4_pressed;                          // KEY4按下标志
    bool key4_last_state;                       // KEY4上次状态
    
    // 显示状态
    uint8 display_refresh_flag;                 // 显示刷新标志
    uint32 last_refresh_time;                   // 上次刷新时间
    
} ui_state_struct;

//=================================================全局变量声明================================================
extern ui_state_struct ui_state;               // UI状态结构

//=================================================函数声明================================================
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     UI系统初始化
// 参数说明     void
// 返回参数     uint8                          初始化结果 (0=成功, 1=失败)
// 使用示例     ui_system_init();
// 备注信息     初始化UI界面和按键GPIO
//-------------------------------------------------------------------------------------------------------------------
uint8 ui_system_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按键检测和处理
// 参数说明     void
// 返回参数     void
// 使用示例     ui_key_process();
// 备注信息     检测按键状态，处理按键事件，更新UI状态
//-------------------------------------------------------------------------------------------------------------------
void ui_key_process(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示主界面
// 参数说明     void
// 返回参数     void
// 使用示例     ui_show_main();
// 备注信息     显示系统主界面，包括当前状态和基本信息
//-------------------------------------------------------------------------------------------------------------------
void ui_show_main(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示参数设置界面
// 参数说明     void
// 返回参数     void
// 使用示例     ui_show_param_setting();
// 备注信息     显示参数设置界面，包括可调参数列表
//-------------------------------------------------------------------------------------------------------------------
void ui_show_param_setting(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示参数调整界面
// 参数说明     void
// 返回参数     void
// 使用示例     ui_show_param_adjust();
// 备注信息     显示当前选择参数的调整界面
//-------------------------------------------------------------------------------------------------------------------
void ui_show_param_adjust(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示运行控制界面
// 参数说明     void
// 返回参数     void
// 使用示例     ui_show_run_control();
// 备注信息     显示系统运行控制界面
//-------------------------------------------------------------------------------------------------------------------
void ui_show_run_control(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     UI主循环处理
// 参数说明     void
// 返回参数     void
// 使用示例     ui_main_loop();
// 备注信息     UI系统主循环，处理显示和按键事件
//-------------------------------------------------------------------------------------------------------------------
void ui_main_loop(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     参数值调整
// 参数说明     param_index                    参数索引
// 参数说明     increment                      调整增量 (正数增加，负数减少)
// 返回参数     uint8                          调整结果 (0=成功, 1=失败)
// 使用示例     ui_adjust_parameter(0, 1.0f);
// 备注信息     调整指定参数的值
//-------------------------------------------------------------------------------------------------------------------
uint8 ui_adjust_parameter(uint8 param_index, float increment);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     保存当前参数设置
// 参数说明     void
// 返回参数     uint8                          保存结果 (0=成功, 1=失败)
// 使用示例     ui_save_parameters();
// 备注信息     保存当前所有参数设置到配置系统
//-------------------------------------------------------------------------------------------------------------------
uint8 ui_save_parameters(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     重置参数到默认值
// 参数说明     void
// 返回参数     uint8                          重置结果 (0=成功, 1=失败)
// 使用示例     ui_reset_parameters();
// 备注信息     将所有参数重置到默认值
//-------------------------------------------------------------------------------------------------------------------
uint8 ui_reset_parameters(void);

// 兼容性宏定义（保持向后兼容）
#define show_open()                 ui_main_loop()
#define key_test()                  ui_key_process()
#define gpio_init_key_ips()         ui_system_init()

#endif
