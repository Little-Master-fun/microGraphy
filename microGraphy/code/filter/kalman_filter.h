#ifndef _KALMAN_FILTER_H_
#define _KALMAN_FILTER_H_

#include "zf_common_typedef.h"
#include <math.h>

//================================================= 宏定义 =================================================

// 滤波器维度定义
#define KF_STATE_DIM            (6)     // 状态维度 [x, y, heading, vx, vy, omega]
#define KF_MEASUREMENT_DIM      (3)     // 测量维度 [encoder_x, encoder_y, gyro_omega]
#define KF_GYRO_STATE_DIM       (2)     // 陀螺仪滤波状态维度 [omega, bias]

// 噪声参数
#define KF_PROCESS_NOISE_POS    (0.1f)  // 位置过程噪声
#define KF_PROCESS_NOISE_VEL    (0.5f)  // 速度过程噪声
#define KF_PROCESS_NOISE_OMEGA  (0.1f)  // 角速度过程噪声
#define KF_PROCESS_NOISE_BIAS   (0.01f) // 偏置过程噪声

#define KF_MEASUREMENT_NOISE_ENCODER (5.0f)  // 编码器测量噪声 (mm)
#define KF_MEASUREMENT_NOISE_GYRO    (0.05f) // 陀螺仪测量噪声 (rad/s)

//================================================= 数据结构定义 =================================================

// 卡尔曼滤波器状态向量
typedef struct {
    float x;        // 位置X (mm)
    float y;        // 位置Y (mm)
    float heading;  // 航向角 (rad)
    float vx;       // X方向速度 (mm/s)
    float vy;       // Y方向速度 (mm/s)
    float omega;    // 角速度 (rad/s)
} kf_state_t;

// 传感器测量数据
typedef struct {
    float encoder_x;    // 编码器积分位置X (mm)
    float encoder_y;    // 编码器积分位置Y (mm)
    float gyro_omega;   // 陀螺仪角速度 (rad/s)
    bool valid;         // 数据有效标志
} kf_measurement_t;

// 卡尔曼滤波器主结构
typedef struct {
    // 状态向量和协方差矩阵
    float state[KF_STATE_DIM];                          // 状态向量
    float P[KF_STATE_DIM][KF_STATE_DIM];               // 状态协方差矩阵
    float Q[KF_STATE_DIM][KF_STATE_DIM];               // 过程噪声协方差矩阵
    float R[KF_MEASUREMENT_DIM][KF_MEASUREMENT_DIM];   // 测量噪声协方差矩阵
    
    // 临时计算矩阵
    float F[KF_STATE_DIM][KF_STATE_DIM];               // 状态转移矩阵
    float H[KF_MEASUREMENT_DIM][KF_STATE_DIM];         // 观测矩阵
    float K[KF_STATE_DIM][KF_MEASUREMENT_DIM];         // 卡尔曼增益
    
    // 滤波器状态
    bool initialized;       // 初始化标志
    uint32_t update_count;  // 更新次数
    float last_time;        // 上次更新时间 (s)
} kalman_filter_t;

// 陀螺仪专用卡尔曼滤波器 (简化版)
typedef struct {
    float state[KF_GYRO_STATE_DIM];     // [角速度, 偏置]
    float P[KF_GYRO_STATE_DIM][KF_GYRO_STATE_DIM];  // 协方差矩阵
    float Q_omega;          // 角速度过程噪声
    float Q_bias;           // 偏置过程噪声
    float R_gyro;           // 陀螺仪测量噪声
    bool initialized;       // 初始化标志
} gyro_kalman_filter_t;

// 滤波性能统计
typedef struct {
    float innovation_x;     // 位置X新息 (mm)
    float innovation_y;     // 位置Y新息 (mm)
    float innovation_omega; // 角速度新息 (rad/s)
    float trace_P;          // 协方差矩阵迹
    uint32_t outlier_count; // 异常值计数
    float consistency_check; // 一致性检验值
} kf_performance_t;

//================================================= 全局变量声明 =================================================
extern kalman_filter_t g_kalman_filter;
extern gyro_kalman_filter_t g_gyro_filter;

//================================================= 核心函数声明 =================================================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化卡尔曼滤波器
// 参数说明     initial_state - 初始状态
// 返回参数     bool - 初始化是否成功
// 使用示例     kalman_filter_init(&init_state);
// 备注信息     设置初始状态和噪声参数
//-------------------------------------------------------------------------------------------------------------------
bool kalman_filter_init(const kf_state_t* initial_state);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     卡尔曼滤波器预测步骤
// 参数说明     dt - 时间步长 (s)
// 返回参数     void
// 使用示例     kalman_filter_predict(0.002f);
// 备注信息     基于运动模型预测下一时刻状态
//-------------------------------------------------------------------------------------------------------------------
void kalman_filter_predict(float dt);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     卡尔曼滤波器更新步骤
// 参数说明     measurement - 传感器测量数据
// 返回参数     bool - 更新是否成功
// 使用示例     kalman_filter_update(&sensor_data);
// 备注信息     融合传感器数据，修正状态估计
//-------------------------------------------------------------------------------------------------------------------
bool kalman_filter_update(const kf_measurement_t* measurement);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取滤波后的状态
// 参数说明     filtered_state - 输出的滤波状态
// 返回参数     void
// 使用示例     kalman_filter_get_state(&current_state);
// 备注信息     获取当前最优状态估计
//-------------------------------------------------------------------------------------------------------------------
void kalman_filter_get_state(kf_state_t* filtered_state);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     重置卡尔曼滤波器
// 参数说明     void
// 返回参数     void
// 使用示例     kalman_filter_reset();
// 备注信息     重置滤波器状态，用于重新初始化
//-------------------------------------------------------------------------------------------------------------------
void kalman_filter_reset(void);

//================================================= 陀螺仪专用滤波器 =================================================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化陀螺仪卡尔曼滤波器
// 参数说明     void
// 返回参数     bool - 初始化是否成功
// 使用示例     gyro_kalman_filter_init();
// 备注信息     专门用于陀螺仪数据滤波和偏置估计
//-------------------------------------------------------------------------------------------------------------------
bool gyro_kalman_filter_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     陀螺仪卡尔曼滤波更新
// 参数说明     raw_gyro - 原始陀螺仪读数 (rad/s)
// 参数说明     dt - 时间步长 (s)
// 返回参数     float - 滤波后的角速度 (rad/s)
// 使用示例     filtered_omega = gyro_kalman_filter_update(raw_omega, 0.002f);
// 备注信息     实时滤波陀螺仪数据，自动估计偏置
//-------------------------------------------------------------------------------------------------------------------
float gyro_kalman_filter_update(float raw_gyro, float dt);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取陀螺仪偏置估计
// 参数说明     void
// 返回参数     float - 当前偏置估计 (rad/s)
// 使用示例     bias = gyro_kalman_filter_get_bias();
// 备注信息     获取实时估计的陀螺仪偏置
//-------------------------------------------------------------------------------------------------------------------
float gyro_kalman_filter_get_bias(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置陀螺仪滤波器噪声参数
// 参数说明     process_noise - 过程噪声标准差
// 参数说明     measurement_noise - 测量噪声标准差
// 返回参数     void
// 使用示例     gyro_kalman_set_noise(0.1f, 0.05f);
// 备注信息     调整滤波器性能
//-------------------------------------------------------------------------------------------------------------------
void gyro_kalman_set_noise(float process_noise, float measurement_noise);

//================================================= 辅助函数声明 =================================================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取卡尔曼滤波性能统计
// 参数说明     void
// 返回参数     const kf_performance_t* - 性能统计数据
// 使用示例     perf = kalman_filter_get_performance();
// 备注信息     用于监控滤波器性能和调试
//-------------------------------------------------------------------------------------------------------------------
const kf_performance_t* kalman_filter_get_performance(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     卡尔曼滤波器调试信息输出
// 参数说明     void
// 返回参数     void
// 使用示例     kalman_filter_print_debug();
// 备注信息     输出详细状态信息，用于调试
//-------------------------------------------------------------------------------------------------------------------
void kalman_filter_print_debug(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置卡尔曼滤波器噪声参数
// 参数说明     process_noise_scale - 过程噪声缩放因子
// 参数说明     measurement_noise_scale - 测量噪声缩放因子
// 返回参数     void
// 使用示例     kalman_filter_set_noise(1.0f, 0.8f);
// 备注信息     动态调整噪声参数以适应不同环境
//-------------------------------------------------------------------------------------------------------------------
void kalman_filter_set_noise(float process_noise_scale, float measurement_noise_scale);

#endif // _KALMAN_FILTER_H_
