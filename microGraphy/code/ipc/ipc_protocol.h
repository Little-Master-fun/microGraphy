#ifndef _IPC_PROTOCOL_H_
#define _IPC_PROTOCOL_H_

#include "zf_common_headfile.h"
#include "navigation_flash_improved.h" // 为了引用VehicleState结构体

//================================================= 消息ID定义 =================================================

// M7_1 -> M7_0 的消息
#define IPC_ID_VEHICLE_STATE     (0x10) // 消息ID：发送车辆状态

// M7_0 -> M7_1 的消息
#define IPC_ID_RESET_ESTIMATOR   (0x20) // 消息ID：命令复位状态估计器
#define IPC_ID_MOTION_COMMAND    (0x30) // 消息ID：发送运动指令 (线速度+角速度)


//================================================= 数据包结构定义 =================================================

// 使用联合体来方便地在 32位整数 和 浮点数 之间转换，以适配IPC的发送机制
typedef union {
    uint32_t u32;
    float    f32;
} ipc_data_converter_t;

#endif // _IPC_PROTOCOL_H_
