#ifndef _STATE_ESTIMATOR_H_
#define _STATE_ESTIMATOR_H_

#include "zf_common_headfile.h"
#include "navigation_flash_improved.h" // 引用核心数据结构 VehicleState
#include "filter/kalman_filter.h"      // 引用卡尔曼滤波器

// 定义车辆物理参数
#define VEHICLE_WHEELBASE_MM    (150.0f)    // 车辆轮距 (mm)

//================================================= 估计器配置 =================================================
typedef enum {
    ESTIMATOR_MODE_SIMPLE = 0,      // 简单死推算
    ESTIMATOR_MODE_KALMAN = 1,      // 卡尔曼滤波器模式
} estimator_mode_t;

//================================================= 对外接口函数 =================================================
void state_estimator_init(void);
void state_estimator_update(float dt);
const VehicleState* state_estimator_get_state(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置状态估计器模式
// 参数说明     mode - 估计器模式
// 返回参数     bool - 设置是否成功
// 使用示例     state_estimator_set_mode(ESTIMATOR_MODE_KALMAN);
//-------------------------------------------------------------------------------------------------------------------
bool state_estimator_set_mode(estimator_mode_t mode);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取当前估计器模式
// 返回参数     estimator_mode_t - 当前模式
//-------------------------------------------------------------------------------------------------------------------
estimator_mode_t state_estimator_get_mode(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取卡尔曼滤波器性能统计
// 返回参数     const kf_performance_t* - 性能统计数据
//-------------------------------------------------------------------------------------------------------------------
const kf_performance_t* state_estimator_get_kalman_performance(void);


#endif // _STATE_ESTIMATOR_H_
